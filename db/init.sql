CREATE SCHEMA if not EXISTS public;

CREATE TYPE "user_status" AS ENUM (
  'active',
  'inactive',
  'deleted',
  'suspended'
);

CREATE TYPE "client_type" AS ENUM (
  'new',
  'recurring'
);

CREATE TYPE "availability_status" AS ENUM (
  'available',
  'unavailable'
);

CREATE TYPE "payment_method" AS ENUM (
  'cash',
  'card',
  'transfer'
);

CREATE TYPE "payment_status" AS ENUM (
  'pending',
  'paid'
);

CREATE TYPE "appointment_status" AS ENUM (
  'pending',
  'completed',
  'cancelled'
);

CREATE TYPE "kardex_movement_type" AS ENUM (
  'supplier_purchase',
  'direct_sale',
  'service_consumption',
  'inventory_count_adjustment',
  'product_return'
);

CREATE TABLE "roles" (
  "id" INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "name" varchar(25) UNIQUE NOT NULL,
  "description" text
);

CREATE TABLE "users" (
  "id" INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "role_id" int NOT NULL,
  "first_name" varchar(25) NOT NULL,
  "last_name" varchar(25) NOT NULL,
  "email" varchar(50) UNIQUE NOT NULL,
  "password" varchar(255) NOT NULL,
  "phone" varchar(20),
  "status" user_status NOT NULL DEFAULT 'active',
  "last_login_at" timestamp,
  "created_at" timestamp NOT NULL DEFAULT (now())
);

CREATE TABLE "clients" (
  "id" INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "first_name" varchar(25) NOT NULL,
  "last_name" varchar(25) NOT NULL,
  "phone" varchar(20),
  "email" varchar(50),
  "address" text,
  "client_type" client_type DEFAULT 'new',
  "notes" text,
  "registered_at" timestamp DEFAULT (now())
);

CREATE TABLE "service_categories" (
  "id" INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "name" varchar(100) NOT NULL,
  "description" text
);

CREATE TABLE "services" (
  "id" INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "category_id" int NOT NULL,
  "name" varchar(50) NOT NULL,
  "description" text,
  "duration_minutes" int NOT NULL,
  "price" decimal(10,2) NOT NULL,
  "availability" availability_status DEFAULT 'available'
);

CREATE TABLE "service_kits" (
  "id" INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "service_id" int NOT NULL,
  "product_id" int NOT NULL,
  "consumed_quantity" decimal(10,2) NOT NULL
);

CREATE TABLE "appointments" (
  "id" INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "client_id" int NOT NULL,
  "employee_id" int NOT NULL,
  "appointment_datetime" timestamp NOT NULL,
  "status" appointment_status DEFAULT 'pending',
  "location" varchar(30) NOT NULL,
  "home_address" text,
  "notes" text,
  "created_at" timestamp DEFAULT (now())
);

CREATE TABLE "appointment_services" (
  "id" INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "appointment_id" int NOT NULL,
  "service_id" int NOT NULL,
  "applied_price" decimal(10,2) NOT NULL
);

CREATE TABLE "suppliers" (
  "id" INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "name" varchar(50) NOT NULL,
  "contact_name" varchar(50),
  "phone" varchar(20),
  "email" varchar(50),
  "address" text,
  "lead_time_days" int NOT NULL DEFAULT 3,
  "safety_stock_days" int NOT NULL DEFAULT 2
);

CREATE TABLE "products" (
  "id" INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "supplier_id" int NOT NULL,
  "barcode" varchar(50) UNIQUE NOT NULL,
  "name" varchar(50) NOT NULL,
  "description" text,
  "purchase_unit" varchar(20) NOT NULL DEFAULT 'box',
  "consumption_unit" varchar(20) NOT NULL DEFAULT 'unit',
  "conversion_factor" decimal(10,2) NOT NULL DEFAULT 1,
  "allows_decimals" boolean NOT NULL DEFAULT false,
  "purchase_price" decimal(10,2) NOT NULL,
  "sale_price" decimal(10,2) NOT NULL
);

CREATE TABLE "kardex" (
  "id" INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "product_id" int NOT NULL,
  "user_id" int NOT NULL,
  "created_at" timestamp NOT NULL DEFAULT (now()),
  "movement_type" kardex_movement_type NOT NULL,
  "reference_document" varchar(50) NOT NULL,
  "quantity" decimal(10,2) NOT NULL,
  "unit_cost" decimal(10,2) NOT NULL,
  "notes" text
);

CREATE TABLE "physical_counts" (
  "id" INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "record_code" varchar(30) UNIQUE NOT NULL,
  "product_id" int NOT NULL,
  "user_id" int NOT NULL,
  "snapshot_at" timestamp NOT NULL,
  "system_snapshot_stock" decimal(10,2) NOT NULL,
  "physical_counted_stock" decimal(10,2) NOT NULL,
  "adjustment_difference" decimal(10,2) NOT NULL
);

CREATE TABLE "invoices" (
  "id" INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "appointment_id" int,
  "client_id" int NOT NULL,
  "user_id" int NOT NULL,
  "issued_at" timestamp NOT NULL DEFAULT (now()),
  "subtotal" decimal(10,2) NOT NULL,
  "tax" decimal(10,2) NOT NULL,
  "total" decimal(10,2) NOT NULL,
  "payment_method" payment_method DEFAULT 'card'
);

CREATE TABLE "invoice_details" (
  "id" INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "invoice_id" int NOT NULL,
  "service_id" int,
  "product_id" int,
  "quantity" decimal(10,2) NOT NULL DEFAULT 1,
  "unit_price" decimal(10,2) NOT NULL,
  "subtotal" decimal(10,2) NOT NULL,
  CONSTRAINT "chk_invoice_detail_item" CHECK (
    ("service_id" IS NOT NULL AND "product_id" IS NULL) OR
    ("service_id" IS NULL AND "product_id" IS NOT NULL)
  )
);

CREATE TABLE "commissions" (
  "id" INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "employee_id" int NOT NULL,
  "invoice_id" int NOT NULL,
  "commission_amount" decimal(10,2) NOT NULL,
  "created_at" timestamp NOT NULL DEFAULT (now()),
  "status" payment_status DEFAULT 'pending'
);

CREATE UNIQUE INDEX ON "service_kits" ("service_id", "product_id");

CREATE UNIQUE INDEX "uq_doc_prod_type" ON "kardex" ("reference_document", "product_id", "movement_type");

CREATE INDEX ON "kardex" ("product_id", "created_at");

